import { _electron, chromium, expect } from '@playwright/test';
import { mkdtemp, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';

const userData = await mkdtemp(path.join(os.tmpdir(), 'qusu-browser-test-'));
const env = { ...process.env, QUSU_TEST_USER_DATA: userData };
delete env.ELECTRON_RUN_AS_NODE;
const executablePath = process.env.QUSU_TEST_EXECUTABLE;
const launch = () => _electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: ['.'] }), env });
let desktop;
let browser;
try {
  desktop = await launch();
  await expect.poll(() => desktop.evaluate(({ app }) => app.qusuEditorURL)).toBe('http://127.0.0.1:17863/');
  expect(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length)).toBe(0);
  await expect.poll(() => desktop.evaluate(({ app }) => app.qusuOpenedURLs)).toEqual(['http://127.0.0.1:17863/']);
  browser = await chromium.launchPersistentContext(path.join(userData, 'browser'), { headless: true, permissions: ['clipboard-read', 'clipboard-write'] });
  let page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:17863/');
  await expect(page.locator('[data-block-id]')).toHaveCount(22);
  expect(await page.evaluate(() => typeof window.require)).toBe('undefined');
  await page.getByLabel('文章主标题', { exact: true }).fill('浏览器安装版持久化验证');
  const image = page.locator('[data-block-type=image]');
  await image.locator('input[type=file]').setInputFiles({ name: 'test.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6kAAAAABJRU5ErkJggg==', 'base64') });
  await expect(image.locator('img')).toHaveAttribute('src', /^data:image/);
  await page.getByRole('button', { name: '复制公众号排版', exact: true }).click();
  await expect(page.locator('.toast')).toContainText('已复制富文本');
  const copied = await page.evaluate(async () => { const items = await navigator.clipboard.read(); return (await items[0].getType('text/html')).text(); });
  expect(copied).toContain('浏览器安装版持久化验证');
  expect(copied).not.toContain('data:image');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存 JSON', exact: true }).click();
  const download = await downloadPromise;
  const exportPath = path.join(userData, 'project.qusu.json');
  await download.saveAs(exportPath);
  expect(JSON.parse(await readFile(exportPath, 'utf8')).blocks.length).toBe(22);
  await expect(page.getByText('已自动保存', { exact: true })).toBeVisible();
  expect((await fetch('http://127.0.0.1:17863/%2e%2e%2fpackage.json')).status).toBe(403);
  const foreignHostStatus = await new Promise((resolve, reject) => {
    http.get('http://127.0.0.1:17863/', { headers: { Host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }).on('error', reject);
  });
  expect(foreignHostStatus).toBe(403);
  expect((await fetch('http://127.0.0.1:17863/', { method: 'POST' })).status).toBe(405);
  expect((await fetch('http://127.0.0.1:17863/missing.js')).status).toBe(404);
  expect(errors).toEqual([]);
  await browser.close(); browser = null;
  await desktop.close(); desktop = await launch();
  await expect.poll(() => desktop.evaluate(({ app }) => app.qusuEditorURL)).toBe('http://127.0.0.1:17863/');
  browser = await chromium.launchPersistentContext(path.join(userData, 'browser'), { headless: true });
  page = await browser.newPage();
  await page.goto('http://127.0.0.1:17863/');
  await expect(page.getByLabel('文章主标题', { exact: true })).toHaveValue('浏览器安装版持久化验证');
  await expect(page.locator('[data-block-type=image] img')).toHaveAttribute('src', /^data:image/);
  console.log('Browser launcher smoke passed: no app window, browser launch, assets, clipboard, JSON download, restart persistence and server boundaries.');
} finally { if (browser) await browser.close(); if (desktop) await desktop.close(); }
